import { readFileSync } from "node:fs";
import { chromium } from "@playwright/test";
const session = JSON.parse(readFileSync("../../.tmp/qa-session.json", "utf8"));
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: 1440, height: 900 } });
await ctx.addCookies([{ name: session.name, value: session.value, domain: "localhost", path: "/", httpOnly: true, sameSite: "Lax" }]);
const page = await ctx.newPage();
const bad = [];
page.on("response", (r) => { if (r.status() >= 400) bad.push(`${r.status()} ${r.url().slice(0, 110)}`); });
await page.goto("http://localhost:3000/fittrack/relive3d/8c24a0f6-f069-4c4e-bc68-61e8f6a867fb", { waitUntil: "domcontentloaded" });
await page.waitForSelector("gmp-map-3d", { timeout: 60000 });
await page.waitForTimeout(6000);
const back = page.getByRole("link", { name: /Activity/ }).first();
console.log("back href:", await back.getAttribute("href"));
await back.click();
await page.waitForTimeout(4000);
console.log("after back:", page.url().replace("http://localhost:3000", ""));
console.log("4xx:", bad.length ? bad : "none");
await browser.close();